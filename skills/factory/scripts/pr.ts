// Pure pull request facts. No I/O here: forge.ts gathers PrFacts, and this
// file turns them into the status agents act on and the checks a merge must
// pass, so both are tested without a network.

export type CheckRun = {
  id?: number;
  name: string;
  check_suite?: { id: number } | null;
  status: string;
  conclusion: string | null;
};
export type CommitStatus = { context: string; state: string };
export type Review = { user: { login: string } | null; state: string };

export type PrFacts = {
  number: number;
  url: string;
  title: string;
  body: string | null;
  state: "open" | "closed";
  merged: boolean;
  draft: boolean;
  mergeable: boolean | null;
  mergeableState: string;
  headSha: string;
  headRef: string;
  baseRef: string;
  updatedAt: string;
  checkRuns: CheckRun[];
  statuses: CommitStatus[];
  reviews: Review[];
  // null when the forge would not tell us; a merge treats that as a blocker.
  unresolvedThreads: number | null;
};

const FAILING_CONCLUSIONS = new Set(["failure", "timed_out", "cancelled", "action_required", "startup_failure", "stale"]);

export type Checks = { failing: string[]; pending: string[]; passing: number };

// A rerun adds a newer run to the same check suite, so only the newest run per
// suite and name counts. Two workflows with a job of the same name are two
// suites, and both count.
export function classifyChecks(runs: CheckRun[], statuses: CommitStatus[]): Checks {
  const latest = new Map<string, CheckRun>();
  for (const run of runs) {
    const key = `${run.check_suite?.id ?? ""}:${run.name}`;
    const prev = latest.get(key);
    if (!prev || (run.id ?? 0) >= (prev.id ?? 0)) latest.set(key, run);
  }
  const out: Checks = { failing: [], pending: [], passing: 0 };
  for (const run of latest.values()) {
    if (run.status !== "completed") out.pending.push(run.name);
    else if (FAILING_CONCLUSIONS.has(run.conclusion ?? "")) out.failing.push(run.name);
    else out.passing++;
  }
  for (const s of statuses) {
    if (s.state === "pending") out.pending.push(s.context);
    else if (s.state === "failure" || s.state === "error") out.failing.push(s.context);
    else out.passing++;
  }
  return out;
}

export type ReviewState = { approved: boolean; changesRequested: string[] };

// Reviews arrive oldest first; a reviewer's latest decisive review wins.
export function classifyReviews(reviews: Review[]): ReviewState {
  const latest = new Map<string, string>();
  for (const r of reviews) {
    const login = r.user?.login;
    if (login && ["APPROVED", "CHANGES_REQUESTED", "DISMISSED"].includes(r.state)) latest.set(login, r.state);
  }
  const changesRequested = [...latest].filter(([, s]) => s === "CHANGES_REQUESTED").map(([l]) => l);
  const approved = changesRequested.length === 0 && [...latest.values()].includes("APPROVED");
  return { approved, changesRequested };
}

// Cloud sessions post through a GitHub proxy that appends this attribution,
// and the CLI adds the same footer to the replies it posts, so a reply from
// the Mac says who wrote it too; in the cloud, the proxy drops its duplicate.
const ATTRIBUTION = /\n+---\n_Generated by \[Claude Code\]\([^)\n]*\)_\s*$/;
const FOOTER = "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_";
export const attributed = (body: string): string => (ATTRIBUTION.test(body) ? body : body + FOOTER);
// Whether an agent wrote a comment, by that footer.
export const byAgent = (body: string): boolean => ATTRIBUTION.test(body);

export type Status = {
  pr: number;
  url: string;
  title: string;
  state: "open" | "merged" | "closed";
  draft: boolean;
  // null while GitHub is still computing it.
  conflicts: boolean | null;
  // GitHub's mergeable_state: clean, unstable, blocked (branch protection
  // wants a review or check), behind, dirty, draft or unknown.
  mergeState: string;
  checks: Checks;
  reviews: ReviewState;
  unresolvedThreads: number | null;
  headSha: string;
  headRef: string;
  baseRef: string;
  updatedAt: string;
};

export function status(f: PrFacts): Status {
  return {
    pr: f.number,
    url: f.url,
    title: f.title,
    state: f.merged ? "merged" : f.state,
    draft: f.draft,
    conflicts: f.mergeable === false || f.mergeableState === "dirty" ? true : f.mergeable === null ? null : false,
    mergeState: f.mergeableState,
    checks: classifyChecks(f.checkRuns, f.statuses),
    reviews: classifyReviews(f.reviews),
    unresolvedThreads: f.unresolvedThreads,
    headSha: f.headSha,
    headRef: f.headRef,
    baseRef: f.baseRef,
    updatedAt: f.updatedAt,
  };
}

// What stops a merge. Every check counts, required or not, since a repo
// without branch protection requires none.
export function mergeBlockers(s: Status): string[] {
  const out: string[] = [];
  if (s.state !== "open") out.push(`it is ${s.state}`);
  if (s.draft) out.push("it is a draft");
  if (s.conflicts === null) out.push("GitHub is still computing whether it conflicts");
  else if (s.conflicts) out.push(`it conflicts with ${s.baseRef}`);
  if (s.checks.failing.length) out.push(`failing: ${s.checks.failing.join(", ")}`);
  if (s.checks.pending.length) out.push(`pending: ${s.checks.pending.join(", ")}`);
  if (s.reviews.changesRequested.length) out.push(`changes requested by ${s.reviews.changesRequested.join(", ")}`);
  if (s.unresolvedThreads === null) out.push("review threads could not be read");
  else if (s.unresolvedThreads > 0) out.push(`${s.unresolvedThreads} open review thread(s)`);
  if (s.mergeState === "behind") out.push(`behind ${s.baseRef}: update the branch`);
  if (s.mergeState === "blocked") out.push("branch protection blocks it: a required review or check");
  return out;
}

// One line per change for `pr watch`: what an agent would act on.
export function fingerprint(s: Status): string {
  return [
    s.state,
    s.draft ? "draft" : "ready",
    s.headSha.slice(0, 7),
    `conflicts=${s.conflicts ?? "?"}`,
    `failing=${s.checks.failing.length}`,
    `pending=${s.checks.pending.length}`,
    `threads=${s.unresolvedThreads ?? "?"}`,
    `changes=${s.reviews.changesRequested.length}`,
  ].join(" ");
}
